/**
 * 七种语言全部维护完整。
 * t() 仍保留回落：万一某个 key 漏翻，会退回 en 而不是显示 key 本身。
 * 加新语言 = 在这里加一整个 Dict，页面/路由/hreflang 全部自动生效。
 */
const DICTS: Record<Lang, Dict> = {
  en,
  'zh-cn': zhCn,
  'zh-tw': zhTw,
  ja,
  fr,
  pt,
  de,
};

export function t(lang: Lang, key: string): string {
  return DICTS[lang]?.[key] ?? en[key] ?? key;
}

/** 工具名/标题等也走同样的回落逻辑 */
export function pick(lang: Lang, text: Partial<Record<Lang, string>> & { en: string }): string {
  return text[lang] ?? text.en;
}
